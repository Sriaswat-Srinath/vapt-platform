"""Report assembly from stored, deterministic data only.

Every number in a report is read back from the database — nothing is recomputed
by a different route, and no prose is generated by a model. The limitations
section is built from what the assessment ACTUALLY covered, so a partial scan
cannot be presented as a complete one.
"""
from __future__ import annotations
import datetime as dt
from typing import Any
from sqlalchemy import select
from sqlalchemy.orm import Session
from .. import models
from ..api.v1.taxonomy_api import _coverage_rows
from .. import coverage as cv

TEMPLATE_KEY = "vapt-standard"
TEMPLATE_VERSION = "1.1.0"

# Every artifact must carry this, in every format. Invariant I10.
SYNTHETIC_STATEMENT = (
    "This assessment covers a locally hosted, deliberately vulnerable synthetic training "
    "application (OWASP Juice Shop) registered as a mock-lab asset. It says nothing about the "
    "security posture of any real production, staging or corporate system, and must not be "
    "presented as if it did."
)


def _severity_order(s: str) -> int:
    return {"critical": 0, "high": 1, "medium": 2, "low": 3, "informational": 4}.get(s, 5)


def build(session: Session, *, asset: models.Asset, job_ids: list[str],
          include_states: tuple[str, ...]) -> list[dict[str, Any]]:
    """Returns ordered section dicts: {key, heading, body_md, data}."""
    now = dt.datetime.now(dt.timezone.utc)
    grant = session.execute(select(models.ScopeGrant).where(
        models.ScopeGrant.asset_id == asset.id).order_by(
        models.ScopeGrant.created_at.desc()).limit(1)).scalar_one_or_none()
    rules = session.execute(select(models.ScopeRule).where(
        models.ScopeRule.asset_id == asset.id)).scalars().all()
    jobs = session.execute(select(models.ScanJob).where(
        models.ScanJob.id.in_(job_ids))).scalars().all() if job_ids else []
    profiles = {p.key: p for p in session.execute(select(models.ScanProfile)).scalars().all()}
    runs = session.execute(select(models.DiscoveryRun).where(
        models.DiscoveryRun.asset_id == asset.id).order_by(
        models.DiscoveryRun.created_at.desc())).scalars().all()
    endpoints = session.execute(select(models.Endpoint).where(
        models.Endpoint.asset_id == asset.id)).scalars().all()
    candidates = session.execute(select(models.CandidateTest).where(
        models.CandidateTest.asset_id == asset.id)).scalars().all()
    all_findings = session.execute(select(models.Finding).where(
        models.Finding.asset_id == asset.id,
        models.Finding.suppressed_at.is_(None))).scalars().all()
    findings = [f for f in all_findings if f.validation_state in include_states]
    findings.sort(key=lambda f: (_severity_order(f.severity), f.title))
    iso = session.execute(select(models.LabIsolationCheck).order_by(
        models.LabIsolationCheck.checked_at.desc()).limit(1)).scalar_one_or_none()

    by_state: dict[str, int] = {}
    for f in all_findings:
        by_state[f.validation_state] = by_state.get(f.validation_state, 0) + 1
    by_sev: dict[str, int] = {}
    for f in findings:
        by_sev[f.severity] = by_sev.get(f.severity, 0) + 1

    detailed: list[dict[str, Any]] = []
    for f in findings:
        risk = session.execute(select(models.RiskScore).where(
            models.RiskScore.finding_id == f.id).order_by(
            models.RiskScore.computed_at.desc()).limit(1)).scalar_one_or_none()
        evidence = session.execute(select(models.Evidence).where(
            models.Evidence.finding_id == f.id).order_by(
            models.Evidence.collected_at)).scalars().all()
        history = session.execute(select(models.ValidationEvent).where(
            models.ValidationEvent.finding_id == f.id).order_by(
            models.ValidationEvent.at)).scalars().all()
        obs = session.execute(select(models.FindingObservation).where(
            models.FindingObservation.finding_id == f.id)).scalars().all()
        provenance = []
        for link in obs[:5]:
            o = session.get(models.RawObservation, link.raw_observation_id)
            if o:
                provenance.append({"adapter": o.adapter_name, "adapter_version": o.adapter_version,
                                   "rule_id": o.adapter_rule_id,
                                   "payload_sha256": o.payload_sha256,
                                   "captured_at": o.captured_at.isoformat()})
        detailed.append({
            "id": str(f.id), "title": f.title, "category": f.category, "severity": f.severity,
            "confidence": f.confidence, "validation_state": f.validation_state,
            "validation_rule_id": f.validation_rule_id,
            "validation_rule_version": f.validation_version,
            "affected_url": f.affected_url, "http_method": f.http_method,
            "parameter_name": f.parameter_name, "catalogue_key": f.catalogue_key,
            "unmapped_rule_id": f.unmapped_rule_id,
            "description_md": f.description_md, "remediation_md": f.remediation_md,
            "coverage_complete": f.coverage_complete, "occurrence_count": f.occurrence_count,
            "cvss": ({"source": risk.cvss_source, "version": risk.cvss_version,
                      "vector": risk.cvss_vector,
                      "base": float(risk.cvss_base) if risk.cvss_base is not None else None}
                     if risk else None),
            "priority_score": (float(risk.priority_score)
                               if risk and risk.priority_score is not None else None),
            "evidence": [{"kind": e.kind, "label": e.label,
                          "redaction_version": e.redaction_version,
                          "content_redacted": e.content_redacted,
                          "redaction_counts": (e.redaction_report or {}).get("counts")}
                         for e in evidence],
            "validation_history": [{"at": h.at.isoformat(), "from_state": h.from_state,
                                    "to_state": h.to_state, "rule_id": h.rule_id,
                                    "actor_kind": h.actor_kind,
                                    "justification": h.justification, "note": h.note}
                                   for h in history],
            "provenance": provenance,
        })

    # ---- taxonomy coverage, including the zeroes ---------------------------
    # The question a reader cannot answer from a findings list alone: what could
    # this assessment have found? Categories with no capability are reported
    # with their zeroes rather than omitted.
    coverage_rows = _coverage_rows(session, asset)
    coverage_summary = cv.summary(coverage_rows)
    tier1 = [r for r in coverage_rows if r.tier == 1]
    silent = [r for r in tier1 if r.detection in (cv.NONE, cv.CATALOGUED)]
    surface_only = [r for r in tier1 if r.detection == cv.SURFACE_ONLY]

    # ---- limitations, derived from what actually happened -----------------
    limitations: list[str] = [SYNTHETIC_STATEMENT]
    if silent:
        limitations.append(
            f"{len(silent)} of {len(tier1)} Tier-1 vulnerability categories were NOT assessable "
            f"by this build: {', '.join(r.display_name for r in silent)}. No detection exists for "
            "them here, so their absence from this report is not evidence of their absence in the "
            "target.")
    if surface_only:
        limitations.append(
            f"{len(surface_only)} further categor(ies) were identified on the attack surface but "
            f"could not be confirmed: {', '.join(r.display_name for r in surface_only)}. "
            "Confirming them requires active or intrusive testing, which is disabled and requires "
            "two independent approvals.")
    fixture_jobs = [j for j in jobs if j.mode == "fixture"]
    live_jobs = [j for j in jobs if j.mode == "live"]
    if fixture_jobs:
        limitations.append(
            f"{len(fixture_jobs)} of {len(jobs)} assessment(s) in this report ran in FIXTURE mode: "
            "they replay recorded scanner output and make no network request to the target. "
            "Findings from them demonstrate the pipeline, not the live application.")
    if not live_jobs:
        limitations.append(
            "No live scan of the target was performed. Scanner execution is disabled and the "
            "authorisation document is unsigned, so no request has been sent to the asset.")
    partial = [j for j in jobs if not j.coverage_complete]
    if partial:
        reasons = sorted({j.stop_reason or "unknown" for j in partial})
        limitations.append(
            f"{len(partial)} assessment(s) did not achieve complete coverage ({', '.join(reasons)}). "
            "Absence of a finding is therefore not evidence of absence: negative-evidence rules "
            "were suppressed and resolved to 'inconclusive'.")
    if by_state.get("inconclusive"):
        limitations.append(
            f"{by_state['inconclusive']} finding(s) are INCONCLUSIVE: the stored evidence does not "
            "settle them either way.")
    if by_state.get("candidate"):
        limitations.append(
            f"{by_state['candidate']} detection(s) remain CANDIDATES because no validation rule "
            "covers them. They are reported rather than dropped, and are not confirmed findings.")
    unmapped = [f for f in all_findings if f.unmapped_rule_id]
    if unmapped:
        limitations.append(
            f"{len(unmapped)} detection(s) came from scanner rules with no catalogue entry, so they "
            "carry no CVSS. They are listed as unmapped detections.")
    limitations.append(
        "Assessment was unauthenticated. Authentication entry points were inventoried, but the "
        "surface behind them is UNASSESSED rather than clean.")
    limitations.append(
        "No active or intrusive testing was performed: it requires an approved profile and two "
        "independent human approvals, which this environment does not have.")
    limitations.append(
        "No platform prioritisation score is computed in this MVP. CVSS, where present, comes from "
        "a curated catalogue and describes the vulnerability class, not this asset's risk.")
    limitations.append(
        "Evidence is not encrypted at application level; host full-disk encryption is assumed and "
        "is not verified by this platform.")

    sections: list[dict[str, Any]] = [
        {"key": "executive_summary", "heading": "Executive summary",
         "body_md": None,
         "data": {"asset_identifier": asset.asset_identifier, "hostname": asset.hostname,
                  "port": asset.port, "environment": asset.environment,
                  "generated_at": now.isoformat(),
                  "findings_reported": len(findings), "findings_total": len(all_findings),
                  "by_validation_state": by_state, "by_severity": by_sev,
                  "assessments": len(jobs), "live_assessments": len(live_jobs),
                  "synthetic_statement": SYNTHETIC_STATEMENT}},
        {"key": "scope", "heading": "Scope",
         "data": {"asset": {"identifier": asset.asset_identifier, "display_name": asset.display_name,
                            "hostname": asset.hostname, "protocol": asset.protocol,
                            "port": asset.port, "environment": asset.environment,
                            "criticality": asset.criticality},
                  "grant": ({"state": grant.state, "document_ref": grant.document_ref,
                             "document_state": grant.document_state,
                             "allowed_cidrs": grant.allowed_cidrs,
                             "allowed_ports": grant.allowed_ports,
                             "allowed_profiles": grant.allowed_profiles,
                             "intrusive_allowed": grant.intrusive_allowed}
                            if grant else None),
                  "rules": [{"kind": r.kind, "host_pattern": r.host_pattern, "port": r.port,
                             "path_prefix": r.path_prefix,
                             "method_allowlist": r.method_allowlist, "reason": r.reason}
                            for r in rules]}},
        {"key": "methodology", "heading": "Scan methodology",
         "data": {"assessments": [{"id": str(j.id), "mode": j.mode, "profile_key": j.profile_key,
                                   "adapter": j.adapter_name, "state": j.state,
                                   "stop_reason": j.stop_reason,
                                   "coverage_complete": j.coverage_complete,
                                   "observations": j.observations_count,
                                   "requests_made": j.requests_made,
                                   "budgets": j.budget_snapshot,
                                   "excluded_paths": (prof.excluded_path_patterns
                                                      if (prof := profiles.get(j.profile_key))
                                                      else None),
                                   "method_denylist": (prof2.method_denylist
                                                       if (prof2 := profiles.get(j.profile_key))
                                                       else None)}
                                  for j in jobs],
                  "isolation_check": ({"checked_at": iso.checked_at.isoformat(),
                                       "isolation_passed": iso.isolation_passed,
                                       "egress_blocked": iso.egress_blocked,
                                       "dns_contained": iso.dns_contained}
                                      if iso else None),
                  "excluded_test_classes": [
                      "denial of service / stress testing", "brute force and credential stuffing",
                      "destructive or state-changing exploitation", "persistence or backdoors",
                      "credential theft", "data exfiltration",
                      "exploitation beyond proof of presence"]}},
        {"key": "attack_surface", "heading": "Discovered attack surface",
         "data": {"discovery_runs": [{"id": str(r.id), "source": r.source, "state": r.state,
                                      "pages_seen": r.pages_seen,
                                      "requests_made": r.requests_made,
                                      "coverage_complete": r.coverage_complete}
                                     for r in runs[:10]],
                  "counts": {"endpoints": len(endpoints),
                             "api_endpoints": sum(1 for e in endpoints if e.is_api),
                             "auth_entry_points": sum(1 for e in endpoints
                                                      if e.auth_entry_kind != "none"),
                             "candidate_tests": len(candidates)},
                  "by_assessment": {s: sum(1 for e in endpoints if e.assessment == s)
                                    for s in ("discovered", "verified", "inferred", "unassessed")
                                    if any(e.assessment == s for e in endpoints)},
                  "auth_entry_points": [{"path": e.path, "kind": e.auth_entry_kind}
                                        for e in endpoints if e.auth_entry_kind != "none"],
                  "candidate_tests": [{"concern": c.concern, "surface_kind": c.surface_kind,
                                       "requires_intrusive": c.requires_intrusive,
                                       "suggested_profile": c.suggested_profile_key}
                                      for c in candidates]}},
        {"key": "vulnerability_summary", "heading": "Vulnerability summary",
         "data": {"by_validation_state": by_state, "by_severity": by_sev,
                  "included_states": list(include_states),
                  "rows": [{"title": f["title"], "severity": f["severity"],
                            "validation_state": f["validation_state"],
                            "cvss_base": (f["cvss"] or {}).get("base"),
                            "affected_url": f["affected_url"]} for f in detailed]}},
        {"key": "findings", "heading": "Individual findings", "data": {"findings": detailed}},
        {"key": "risk_prioritisation", "heading": "Risk prioritisation",
         "data": {"method": ("CVSS v3.1 from the curated vulnerability catalogue, shown alongside "
                             "the scanner's normalised severity. No platform prioritisation score "
                             "is computed in this MVP, so that column is intentionally empty."),
                  "rows": [{"title": f["title"], "severity": f["severity"],
                            "cvss_base": (f["cvss"] or {}).get("base"),
                            "cvss_vector": (f["cvss"] or {}).get("vector"),
                            "cvss_source": (f["cvss"] or {}).get("source"),
                            "priority_score": f["priority_score"]} for f in detailed]}},
        {"key": "remediation", "heading": "Remediation recommendations",
         "data": {"items": [{"title": f["title"], "severity": f["severity"],
                             "remediation_md": f["remediation_md"],
                             "affected_url": f["affected_url"]}
                            for f in detailed if f["remediation_md"]]}},
        {"key": "coverage", "heading": "Taxonomy coverage",
         "data": {"summary": coverage_summary,
                  "categories": [r.as_dict() for r in coverage_rows],
                  "method": ("Coverage is counted, not estimated: catalogue entries, rule packs "
                             "that can reach a verdict, flagged surfaces and stored findings, per "
                             "category. A category with no capability is listed with its zeroes.")}},
        {"key": "limitations", "heading": "Limitations of this assessment",
         "data": {"items": limitations}},
    ]
    for i, section in enumerate(sections):
        section["seq"] = i
        section.setdefault("body_md", None)
    return sections
